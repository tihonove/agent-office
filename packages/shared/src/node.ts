import type { ArtifactId, FactId, NodeId } from './ids.ts'
import type { Fields, Kind, State } from './words.ts'

/**
 * Узел — элемент дерева работы: цель, заявка, единица…
 *
 * Узел раздаётся ролям, пока он лист. Породив детей, он становится учётным:
 * агентов на него больше не поднимают, а его состояние выводится из детей переходами манифеста.
 */
export type Node = {
    id: NodeId
    kind: Kind
    state: State
    parent?: NodeId
    fields: Fields

    /** Если узел порождён артефактом: каким и каким по счёту элементом его списка `nodes`. */
    bornFrom?: { artifact: ArtifactId; index: number }

    /**
   * Эпоха состояния: факт, которым узел вошёл в текущее состояние.
   * Ответы человека, исходы ролей и вердикты действительны только в своей эпохе —
   * поэтому второй заход на «приёмку» не видит ответа, данного в первый.
   */
    since: FactId
}
