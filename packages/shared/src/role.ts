import type { Condition } from './condition.ts'
import type { ArtifactKind, ExecutorName, FieldName, Outcome, State, Takes } from './words.ts'

/**
 * Роль — кто и когда нужен узлу. Объявляется в манифесте; офис лишь сверяет:
 * где предикат истинен, узел дозрел, а агента нет — там агента надо поднять.
 */
export type Role = {
    /** Кто исполняет — имя из раздела `executors`. */
    executor: ExecutorName

    /** Промпт роли: путь относительно каталога манифеста. */
    prompt: string

    /** Предикат: на каких узлах нужен агент этой роли. */
    when: Condition

    /** Требования к входу — зрелость узла. Нет этих полей — роль не поднимается, узел ждёт того, кто их добавит. */
    needs?: FieldName[]

    /** Правило проекции: какие артефакты роли нужны. В проекцию попадёт пересечение с аудиторией артефактов. */
    sees?: SeesRule[]

    /** Стрелки: как заход роли двигает состояние узла. */
    arrows?: Arrows

    /** Что берёт из `resources` сверх исполнителя; по одноимённому ресурсу роль перекрывает исполнителя. */
    takes?: Takes
}

export type SeesRule = {
    /** Вид артефакта; `'*'` — любой. */
    kind: ArtifactKind | '*'
    /** Чьи артефакты брать. По умолчанию — только самого узла. */
    from?: ('self' | 'ancestors' | 'children')[]
}

/**
 * Стрелки — переходы вокруг захода роли. Агент состояние не двигает: он заявляет исход, а стрелку применяет офис.
 * Пропал агент — узел возвращается туда, откуда его увела стрелка `start`.
 */
export type Arrows = {
    /** Состояние узла, пока роль на нём работает. Уводит узел из-под предиката, чтобы тот не сработал дважды. */
    start?: State
    /** Заявленный исход → состояние узла. Если задано, других исходов роль заявить не может. */
    outcomes?: Record<Outcome, State>
}
